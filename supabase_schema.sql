-- 다온테크 ERP - Supabase(PostgreSQL)용 테이블 생성 SQL
-- Supabase > SQL Editor 에 전체 붙여넣고 Run 한 번만 실행
-- (기존 MySQL용 daon.sql / *_migration.sql 5개를 하나로 합친 것)
-- =========================================================

-- 1. 상품
CREATE TABLE IF NOT EXISTS product (
    product_code  VARCHAR(20) PRIMARY KEY,
    product_name  VARCHAR(100) NOT NULL,
    type          VARCHAR(20)  NOT NULL,
    color         VARCHAR(50),
    category      VARCHAR(50),
    use_yn        CHAR(1)      NOT NULL DEFAULT 'Y',
    price         INT          NOT NULL DEFAULT 0,
    created_by    VARCHAR(50),
    updated_by    VARCHAR(50),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. 현재고
CREATE TABLE IF NOT EXISTS product_stock (
    product_code VARCHAR(20) PRIMARY KEY,
    quantity     INT NOT NULL DEFAULT 0
);

-- 3. 거래처
CREATE TABLE IF NOT EXISTS customer (
    customer_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    manager_name  VARCHAR(50),
    phone         VARCHAR(30),
    email         VARCHAR(100),
    address       VARCHAR(255),
    memo          VARCHAR(500),
    use_yn        CHAR(1)   NOT NULL DEFAULT 'Y',
    created_by    VARCHAR(50),
    updated_by    VARCHAR(50),
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. 입출고 이력
CREATE TABLE IF NOT EXISTS product_stock_history (
    stock_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code     VARCHAR(20) NOT NULL,
    type             VARCHAR(20) NOT NULL,
    quantity         INT NOT NULL,
    balance_after    INT NOT NULL DEFAULT 0,
    customer_id      BIGINT,
    memo             VARCHAR(255),
    created_by       VARCHAR(50),
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    cancel_yn        CHAR(1) NOT NULL DEFAULT 'N',
    cancelled_by     VARCHAR(50),
    cancelled_at     TIMESTAMP
);

-- 5. 수주(주문)
CREATE TABLE IF NOT EXISTS sales_order (
    order_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      VARCHAR(40) NOT NULL UNIQUE,
    customer_id   BIGINT NOT NULL REFERENCES customer(customer_id),
    product_code  VARCHAR(30) NOT NULL REFERENCES product(product_code),
    ordered_qty   INT NOT NULL,
    produced_qty  INT NOT NULL DEFAULT 0,
    defective_qty INT NOT NULL DEFAULT 0,
    shipped_qty   INT NOT NULL DEFAULT 0,
    unit_price    DECIMAL(14,0) NOT NULL DEFAULT 0,
    total_amount  DECIMAL(16,0) NOT NULL DEFAULT 0,
    order_date    DATE NOT NULL,
    due_date      DATE NOT NULL,
    order_status  VARCHAR(20) NOT NULL DEFAULT 'ORDERED',
    memo          VARCHAR(500),
    created_by    VARCHAR(50),
    updated_by    VARCHAR(50),
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sales_order_due_status ON sales_order(due_date, order_status);

-- 6. 직원
CREATE TABLE IF NOT EXISTS employee (
    employee_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code          VARCHAR(30) NOT NULL UNIQUE,
    employee_name          VARCHAR(100) NOT NULL,
    department             VARCHAR(100),
    position_name          VARCHAR(100),
    phone                  VARCHAR(50),
    email                  VARCHAR(150),
    hire_date              DATE,
    employment_status      VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    use_yn                 CHAR(1) NOT NULL DEFAULT 'Y',
    hourly_wage            DECIMAL(14,2) NOT NULL DEFAULT 0,
    weekly_scheduled_hours DECIMAL(6,2)  NOT NULL DEFAULT 40,
    weekly_scheduled_days  INT           NOT NULL DEFAULT 5,
    daily_scheduled_hours  DECIMAL(6,2)  NOT NULL DEFAULT 8,
    annual_leave_total     DECIMAL(5,1)  NOT NULL DEFAULT 15.0,
    resume_original_name   VARCHAR(255),
    resume_stored_name     VARCHAR(255),
    memo                   TEXT,
    created_by             VARCHAR(50),
    updated_by             VARCHAR(50),
    created_at             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_employee_status ON employee(employment_status);

-- 7. 연차 사용 이력
CREATE TABLE IF NOT EXISTS employee_leave_history (
    leave_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id      BIGINT NOT NULL REFERENCES employee(employee_id),
    leave_date       DATE NOT NULL,
    days             DECIMAL(4,1) NOT NULL,
    leave_type       VARCHAR(30) NOT NULL DEFAULT 'ANNUAL',
    memo             VARCHAR(500),
    created_by       VARCHAR(50),
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_employee_leave_date ON employee_leave_history(employee_id, leave_date);

-- 8. 급여
CREATE TABLE IF NOT EXISTS employee_payroll (
    payroll_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT NOT NULL REFERENCES employee(employee_id),
    pay_month       CHAR(7) NOT NULL,
    base_salary     DECIMAL(14,0) NOT NULL DEFAULT 0,
    allowance       DECIMAL(14,0) NOT NULL DEFAULT 0,
    extra_allowance DECIMAL(14,0) NOT NULL DEFAULT 0,
    deduction       DECIMAL(14,0) NOT NULL DEFAULT 0,
    net_salary      DECIMAL(14,0) NOT NULL DEFAULT 0,
    payment_status  VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    payment_date    DATE,
    memo            VARCHAR(500),
    created_by      VARCHAR(50),
    updated_by      VARCHAR(50),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_employee_pay_month UNIQUE (employee_id, pay_month)
);

-- 9. 작업 수당(도마 수량 / 연장근무)
CREATE TABLE IF NOT EXISTS employee_work_allowance (
    work_allowance_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id         BIGINT NOT NULL REFERENCES employee(employee_id),
    work_date           DATE NOT NULL,
    board_quantity      INT NOT NULL DEFAULT 0,
    board_unit_price    DECIMAL(14,2) NOT NULL DEFAULT 0,
    board_allowance     DECIMAL(14,0) NOT NULL DEFAULT 0,
    overtime_hours      DECIMAL(6,2)  NOT NULL DEFAULT 0,
    hourly_wage         DECIMAL(14,2) NOT NULL DEFAULT 0,
    overtime_multiplier DECIMAL(4,2)  NOT NULL DEFAULT 1.50,
    overtime_allowance  DECIMAL(14,0) NOT NULL DEFAULT 0,
    total_allowance     DECIMAL(14,0) NOT NULL DEFAULT 0,
    attended            BOOLEAN NOT NULL DEFAULT TRUE,
    memo                VARCHAR(500),
    created_by          VARCHAR(50),
    updated_by          VARCHAR(50),
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_employee_work_date UNIQUE (employee_id, work_date)
);

-- 10. 로그인 사용자
CREATE TABLE IF NOT EXISTS app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(50)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    use_yn        CHAR(1)      NOT NULL DEFAULT 'Y',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 11. 작업 기록(감사 로그)
CREATE TABLE IF NOT EXISTS audit_log (
    audit_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50) NOT NULL,
    action_type VARCHAR(30) NOT NULL,
    target_type VARCHAR(30) NOT NULL,
    target_id   VARCHAR(100),
    details     VARCHAR(1000),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_created_at ON audit_log(created_at);
CREATE INDEX IF NOT EXISTS idx_audit_username  ON audit_log(username);


